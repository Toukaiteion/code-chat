/**
 * 「复制项目时跳过哪些目录」——**唯一的事实源**。
 *
 * ★ 为什么它住在 `shared/` 而不是主进程的 `infra/fs-ops.ts`：
 *   **界面必须把这张清单显示给用户**（§8.2）。跳过什么如果是静默的，
 *   用户会以为整个目录都复制过来了 —— 那是「数据丢失」和「我们知道但没说」
 *   之间最坏的一种组合。而渲染进程 import 不了 `src/main/**`
 *   （那边会拖进 `node:fs`），所以两边共用的事实必须放在两者都能到的地方。
 *
 * 判据是**可重装**：清单里的内容都能由源码 + 锁文件重建，
 * 复制它们只会让一次导入从「几秒」变成「几分钟」，却带不来任何信息。
 *
 * `.git` **刻意不在清单里** —— 历史是拷贝不出来的（§8.2）。
 * 也**刻意不看 `.gitignore`**：那需要跑一次 git（§1.5 限定我们只在导入时用 git），
 * 且 `.gitignore` 表达的是「不进版本库」，与「不值得复制」是两回事。
 * 记在 §8.9 作为可能的改进。
 *
 * ⚠️ 按**目录名**（basename、任意深度）匹配，且只在对方**确实是目录**时才跳过。
 *    一个叫 `build` 的**文件**（用户写的脚本）不该被丢掉 —— 见 `fs-ops.isSkippedDirName`
 *    的调用点，那里用 `stat` 确认过。
 */
export const COPY_SKIP_DIRS: readonly string[] = [
  'node_modules',
  '.venv',
  'venv',
  '__pycache__',
  'dist',
  'build',
  '.next',
  '.turbo',
  '.cache',
  'target',
  'coverage'
]
